/**
 * MySQL Connection Pool & Transaction Helper (`backend/src/config/db.js`)
 * Uses parameterized prepared statements to prevent SQL injection and supports
 * ACID database transactions for payroll generation and finalization.
 */
const mysql = require('mysql2/promise');

const pool = mysql.createPool({
  host: process.env.DB_HOST || '127.0.0.1',
  port: Number(process.env.DB_PORT || 3306),
  user: process.env.DB_USER || 'root',
  password: process.env.DB_PASSWORD || '',
  database: process.env.DB_NAME || 'attendance_payroll_db',
  waitForConnections: true,
  connectionLimit: Number(process.env.DB_CONNECTION_LIMIT || 10),
  queueLimit: 0,
  decimalNumbers: true,
  timezone: '+05:30',
});

/**
 * Executes a callback inside an ACID MySQL transaction (BEGIN -> COMMIT / ROLLBACK)
 * Required for payroll generation, payroll finalization, and attendance corrections.
 */
async function withTransaction(callback) {
  const connection = await pool.getConnection();
  try {
    await connection.beginTransaction();
    const result = await callback(connection);
    await connection.commit();
    return result;
  } catch (error) {
    await connection.rollback();
    throw error;
  } finally {
    connection.release();
  }
}

module.exports = {
  pool,
  withTransaction,
};
